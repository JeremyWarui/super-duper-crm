"""One router per resource, all mounted under /api."""

from fastapi import APIRouter

from backend.api.routers import (
    account,
    admin,
    agents,
    aspirant_site,
    assignments,
    auth,
    branch_officials,
    campaigns,
    candidates,
    console_ops,
    events,
    files,
    geography,
    join,
    messages,
    mobilizers,
    party,
    party_aspirants,
    party_console,
    party_feed,
    party_members,
    party_messages,
    party_nominations,
    party_volunteers,
    party_workspace,
    pay,
    payments,
    payments_in,
    privacy,
    setup,
    site,
    sms_callbacks,
    strategy,
    supporters,
    targets,
    team,
    team_signup,
    users,
    workspace_site,
)

api_router = APIRouter(prefix="/api")
for module in (
    setup,
    branch_officials,
    auth,
    account,
    admin,
    console_ops,
    join,
    geography,
    files,
    campaigns,
    candidates,
    targets,
    mobilizers,
    site,
    party_workspace,
    party,
    party_aspirants,
    party_console,
    party_members,
    party_messages,
    party_nominations,
    party_volunteers,
    events,
    pay,
    payments,
    payments_in,
    supporters,
    messages,
    party_feed,
    sms_callbacks,
    strategy,
    team,
    team_signup,
    agents,
    assignments,
    users,
    workspace_site,
    aspirant_site,
    privacy,
):
    api_router.include_router(module.router)
for module in (admin, candidates, party, payments_in):
    api_router.include_router(module.party_router)
api_router.include_router(privacy.office_router)

__all__ = ["api_router"]
